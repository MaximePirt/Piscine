#include <stdio.h>

int	 create_tab(int tab[4][4], char *arg)
{
	int i;
	int j;
	int count;

	i = 0;
	j = 0;
	count = 0;
	while (count < 32)
	{
		tab[j][i] = arg[count] - '0';
		i++;
		count += 2;
	}
	
}
