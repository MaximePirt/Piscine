#include <unistd.h>
#include <stdio.h>
void print_board(int board[4][4])
{
	int		i;
	int		j;
	char	c;

	i = 0;
	j = 0;
	
	while (i <= 3)
	{
		while (j <= 3)
		{
			c = board[i][j] + '0';
			write(1, &c, 1);
			write(1, " ", 1);
			j++;
		}
		write(1, "\n", 1);
		i++;
		j = 0;
	}
}
