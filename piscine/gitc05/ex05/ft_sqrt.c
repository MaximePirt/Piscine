int	ft_sqrt(int nb)
{
	int	i;
	int	j;

j = 0;
i = 1;
	while (nb > 0)
	{
	nb = nb - i;
	i = i + 2;
	j++;
	}
	if (nb % 10 != 0)
		return (0);
	return (j);
}
