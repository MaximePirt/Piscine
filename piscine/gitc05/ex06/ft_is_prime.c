int	ft_is_prime(int nb)
{
	int	j;

j = 2;
	if (nb <= 1)
		return (0);
	while (j < nb - 1 && j < 46322)
	{
		if (nb % j == 0)
			return (0);
		j++;
	}
	return (1);
}
