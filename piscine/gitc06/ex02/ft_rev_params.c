#include <unistd.h>

void	ft_putchar(char *str)
{
	while (*str != '\0')
	{
		write(1, str, 1);
		str++;
	}
	write(1, "\n", 1);
}

int	main(int argc, char *argv[])
{
	int	n;

n = argc -1;
	while (n != 0)
	{
		ft_putchar(argv[n]);
		n--;
	}
}
